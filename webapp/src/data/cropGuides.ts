export function getCropGuide(name: string): CropGuide | undefined {
  return cropGuides.find((c) => c.name === name || name.includes(c.name))
}

export function searchCropGuides(q: string): CropGuide[] {
  if (!q.trim()) return cropGuides
  const lower = q.toLowerCase()
  return cropGuides.filter(
    (c) =>
      c.name.toLowerCase().includes(lower) ||
      c.category.toLowerCase().includes(lower) ||
      c.commonPests.some((p) => p.toLowerCase().includes(lower)) ||
      c.commonDiseases.some((d) => d.toLowerCase().includes(lower))
  )
}

export function getWeatherSuitability(guide: CropGuide, temp: number, humidity: number): 'good' | 'warning' | 'bad' {
  if (temp >= guide.minTemp && temp <= guide.maxTemp && humidity >= guide.minHumidity && humidity <= guide.maxHumidity) {
    return 'good'
  }
  if ((temp >= guide.minTemp - 3 && temp <= guide.maxTemp + 3) || (humidity >= guide.minHumidity - 10 && humidity <= guide.maxHumidity + 10)) {
    return 'warning'
  }
  return 'bad'
}

export function getWeatherAdvice(guide: CropGuide, temp: number, humidity: number): string {
  if (temp < guide.minTemp - 5) return `⚠️ ${guide.name}는 서리/한파에 취약합니다. 비닐하우스나 방한 대책이 필요합니다.`
  if (temp > guide.maxTemp + 5) return `⚠️ ${guide.name}는 고온에 취약합니다. 그늘막 및 충분한 급수가 필요합니다.`
  if (humidity > guide.maxHumidity + 10) return `⚠️ 습도가 너무 높습니다. ${guide.name}의 병해 발생 위험이 높아요. 환기를 강화하세요.`
  if (humidity < guide.minHumidity - 10) return `⚠️ 습도가 너무 낮습니다. ${guide.name}의 생육이 저하될 수 있어요. 분무 급수를 고려하세요.`
  if (temp >= guide.minTemp && temp <= guide.maxTemp && humidity >= guide.minHumidity && humidity <= guide.maxHumidity) {
    return `✅ ${guide.name} 재배에 최적인 날씨입니다.`
  }
  return `⚠️ ${guide.name} 재배 적정 조건에서 벗어났습니다. 관리에 주의하세요.`
}

export function calculateHarvestDate(plantingDate: string, harvestDays: number): string {
  const d = new Date(plantingDate)
  d.setDate(d.getDate() + harvestDays)
  return d.toISOString().slice(0, 10)
}

export function getDaysUntil(dateString: string): number {
  const target = new Date(dateString)
  const today = new Date()
  target.setHours(0, 0, 0, 0)
  today.setHours(0, 0, 0, 0)
  return Math.ceil((target.getTime() - today.getTime()) / (1000 * 60 * 60 * 24))
}
